export type IpoType = 'IPO' | 'SPO' | 'Pre-IPO' | 'Buyback'
export type IpoStatus = 'Размещено' | 'Объявлено' | 'Ожидается' | 'Отменено' | 'Перенесено'

export interface IpoEvent {
  id: string
  company: string
  fullName?: string
  ticker?: string
  type: IpoType
  exchange: string
  status: IpoStatus
  date: string
  dateApprox?: boolean
  pricePerShare?: number
  priceRangeFrom?: number
  priceRangeTo?: number
  raiseMn?: number
  valuationBn?: number
  freefloat?: number
  bookrunner?: string[]
  sectorId: string
  sector: string
  description: string
  sourceName: string
  sourceUrl: string
}

function searchUrl(site: 'rbc' | 'kommersant' | 'vedomosti' | 'forbes' | 'interfax' | 'moex' | 'tass' | 'smartlab', query: string): string {
  const q = encodeURIComponent(query)
  switch (site) {
    case 'rbc':        return `https://www.rbc.ru/search/?query=${q}`
    case 'kommersant': return `https://www.kommersant.ru/search/results?search_query=${q}`
    case 'vedomosti':  return `https://www.vedomosti.ru/search?query=${q}`
    case 'forbes':     return `https://www.forbes.ru/search?query=${q}`
    case 'interfax':   return `https://www.interfax.ru/search/?sw=${q}`
    case 'moex':       return `https://www.moex.com/ru/search.aspx?query=${q}`
    case 'tass':       return `https://tass.ru/search?query=${q}`
    case 'smartlab':   return `https://smart-lab.ru/q/shares/search/?q=${q}`
  }
}

